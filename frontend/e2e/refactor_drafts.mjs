import assert from 'node:assert/strict';
import { withFixture, fixtureApi, login } from './support/fixture.mjs';

const base = process.env.REFACTOR_E2E_BASE ?? 'http://127.0.0.1:5601';
await withFixture(base, async (browser, cleanup) => {
  const api = await fixtureApi(base);
  const original = await api('GET', '/budgets');
  cleanup(() => api('PUT', `/budgets/${original.period_key}`, { total: original.total.budget, items: original.categories.filter((c) => c.budget).map((c) => ({ category_id: c.category_id, amount: c.budget })) }));
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, timezoneId: 'Asia/Shanghai' });
  const page = await context.newPage();
  try {
    await login(page, base);
    await page.goto(base + '/budgets');
    const total = page.locator('[data-budget="total"] input');
    await total.fill('9000');
    const month = page.locator('.ant-picker input');
    const current = await month.inputValue();
    const next = current.endsWith('-12') ? `${Number(current.slice(0, 4)) + 1}-01` : `${current.slice(0, 4)}-${String(Number(current.slice(5)) + 1).padStart(2, '0')}`;
    await month.fill(next); await month.press('Enter');
    await page.locator('.ant-modal-confirm-title').filter({ hasText: '放弃未保存的预算修改？' }).waitFor();
    await page.getByRole('button', { name: /保留修改/ }).click();
    await page.getByRole('button', { name: /保留修改/ }).waitFor({ state: 'hidden' });
    assert.equal(await month.inputValue(), current);
    assert.equal(Number(await total.inputValue()), 9000);
    await month.fill(next); await month.press('Enter');
    await page.getByRole('button', { name: /放弃并切换/ }).click();
    await page.locator(`[data-period="${next}"]`).waitFor();
    assert.notEqual(Number(await total.inputValue()), 9000);
    await month.fill(current); await month.press('Enter');
    await page.locator(`[data-period="${current}"]`).waitFor();
    await total.fill('9000');
    await page.getByRole('button', { name: /保\s*存/ }).click();
    await page.getByText('有未保存修改').waitFor({ state: 'hidden' });
    assert.equal(Number(await total.inputValue()), 9000);
    console.log('PASS budget cancel, confirm switch and server-confirmed save');
    await page.goto(base + '/liabilities');
    // Finish session restoration/cookie rotation before another document navigation.
    await page.locator('.liability-accounts').waitFor();
    const account = (await api('GET', '/accounts')).find((row) => row.type === 'liability');
    await page.goto(base + '/liabilities/' + account.id);
    await page.getByRole('button', { name: /账户设置/ }).click();
    const dialog = page.getByRole('dialog', { name: '账户设置', exact: true });
    const name = dialog.locator('input[placeholder*="招商信用卡"]');
    await name.fill('未提交名称');
    const restore = { name: account.name, type: account.type, opening_balance: account.opening_balance, liability_type: account.liability_type, sort: account.sort, status: account.status };
    cleanup(() => api('PUT', `/accounts/${account.id}`, restore));
    await api('PUT', `/accounts/${account.id}`, { ...restore, name: account.name + '（服务器更新）' });
    const response = page.waitForResponse((reply) => reply.url().includes(`/accounts/${account.id}/liability`));
    await page.evaluate(() => { window.dispatchEvent(new Event('offline')); window.dispatchEvent(new Event('online')); });
    await response;
    await page.waitForTimeout(100);
    assert.equal(await name.inputValue(), '未提交名称');
    await dialog.getByRole('button', { name: /取\s*消/ }).click();
    console.log('PASS personal account draft survives background detail reload');
    await dialog.waitFor({ state: 'hidden' });
    const second = (await api('GET', '/accounts')).find((row) => row.type === 'liability' && row.id !== account.id);
    await page.goto(base + '/liabilities/' + second.id);
    await page.getByRole('button', { name: /账户设置/ }).click();
    const nextDialog = page.getByRole('dialog', { name: '账户设置', exact: true });
    assert.equal(await nextDialog.locator('input[placeholder*="招商信用卡"]').inputValue(), second.name);
    await nextDialog.getByRole('button', { name: /取\s*消/ }).click();
    await nextDialog.waitFor({ state: 'hidden' });
    let release;
    const delayed = new Promise((resolve) => { release = resolve; });
    await page.route('**/api/v1/accounts/liability-types', async (route) => { await delayed; await route.continue(); });
    await page.goto(base + '/liabilities');
    await page.getByRole('button', { name: /新增负债账户/ }).click();
    const fresh = page.getByRole('dialog', { name: '新增负债账户', exact: true });
    await fresh.locator('input[placeholder*="招商信用卡"]').fill('迟到目录草稿');
    await fresh.locator('#personal-liability_statement_day').fill('20');
    const catalog = page.waitForResponse((reply) => reply.url().endsWith('/accounts/liability-types'));
    release(); await catalog;
    await page.waitForTimeout(100);
    assert.equal(await fresh.locator('input[placeholder*="招商信用卡"]').inputValue(), '迟到目录草稿');
    assert.equal(Number(await fresh.locator('#personal-liability_statement_day').inputValue()), 20);
    await fresh.getByRole('button', { name: /取\s*消/ }).click();
    console.log('PASS switching edit targets and late catalog preserve the right draft');
  } finally { await context.close(); }
});
