import assert from 'node:assert/strict';
import { withFixture, fixtureApi, login, until } from './support/fixture.mjs';

const base = process.env.REFACTOR_E2E_BASE ?? 'http://127.0.0.1:5601';
const prefix = 'interactions-' + crypto.randomUUID();
await withFixture(base, async (browser, cleanup) => {
  const api = await fixtureApi(base);
  const accounts = await api('GET', '/accounts');
  const account = accounts.find((entry) => entry.type === 'asset' && entry.status === 'active');
  const forest = await api('GET', '/categories');
  const category = forest.flatMap((wrapper) => wrapper.children ?? []).flatMap((root) => root.children?.length ? root.children : [root]).find((entry) => entry.kind === 'expense');
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  const page = await context.newPage();
  await login(page, base);
  for (let i = 0; i < 25; i++) {
    const row = await api('POST', '/transactions', { kind: 'expense', amount: '1.23', account_id: account.id, category_id: category.id, entry_date: '2026-10-12', note: prefix + i });
    cleanup(() => api('DELETE', `/transactions/${row.id}`));
  }
  let reads = 0;
  page.on('request', (request) => { if (request.method() === 'GET' && new URL(request.url()).pathname === '/api/v1/transactions') reads++; });
  const target = base + '/records?keyword=' + prefix;
  await page.goto(target);
  await until(() => page.locator('[data-txn-id]').count(), (count) => count === 20, 'desktop first page');
  const first = await page.locator('[data-txn-id]').first().getAttribute('data-txn-id');
  const money = await page.locator(`[data-txn-id="${first}"] .money`).first().innerText();
  await page.setViewportSize({ width: 360, height: 800 });
  await page.locator('.txn-row').first().waitFor();
  assert.equal(await page.locator(`[data-txn-id="${first}"] .money`).first().innerText(), money);
  const length = await page.evaluate(() => history.length);
  await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight));
  await until(() => page.locator('.txn-row').count(), (count) => count === 25, 'append next page');
  assert.equal(new URL(page.url()).searchParams.get('page'), '2');
  assert.equal(await page.evaluate(() => history.length), length, 'append replaces URL');
  assert.equal(await page.locator('.txn-row').evaluateAll((rows) => new Set(rows.map((row) => row.dataset.txnId)).size), 25, 'append has no duplicate rows');
  await page.locator('.ant-pagination-item-1').click();
  await until(() => page.locator('.txn-row').count(), (count) => count === 20, 'explicit pagination resets append');
  assert.equal(await page.evaluate(() => scrollY), 0);
  await page.goBack();
  await until(() => page.locator('.txn-row').count(), (count) => count === 5, 'POP starts at URL page 2');
  await page.goto(target);
  await page.locator('.txn-row').first().waitFor();
  const beforeCancel = reads;
  for (const [type, y] of [['touchstart', 10], ['touchmove', 140], ['touchcancel', 140], ['touchend', 140]]) {
    await page.locator('.txn-list').evaluate((element, { type, y }) => { const event = new Event(type, { bubbles: true }); Object.defineProperty(event, 'touches', { value: [{ clientY: y }] }); element.dispatchEvent(event); }, { type, y });
  }
  await page.waitForTimeout(350);
  assert.equal(reads, beforeCancel, 'touchcancel prevents refresh');
  await page.evaluate((locateId) => history.replaceState({ ...history.state, usr: { locateId: Number(locateId) } }, ''), first);
  await page.reload();
  await until(() => page.locator('.txn-row.flash').count(), (count) => count === 1, 'one-time locator');
  assert.equal(await page.evaluate(() => history.state.usr), null);
  await until(() => page.locator('.txn-row.flash').count(), (count) => count === 0, 'locator timer cleans highlight');
  await page.goto(base + '/mine');
  assert.equal(await page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--kb-inset').trim()), '0px');
  console.log('PASS desktop/mobile values, append/REPLACE, pagination/POP, touchcancel, locate and unmount cleanup');

  await page.goto(base + '/recurring');
  await page.getByRole('button', { name: /新建周期/ }).click();
  const dialog = page.getByRole('dialog', { name: '新建周期模板' });
  await dialog.getByPlaceholder('0.00').fill('12.34');
  await dialog.locator('.cat-leaves .ant-tag').first().click();
  await dialog.locator('.ant-select').click();
  await page.locator('.ant-select-dropdown:visible .ant-select-item-option-content').filter({ hasText: account.name }).first().click();
  await dialog.getByPlaceholder('首次生成日期').fill('2099-01-01');
  await dialog.getByPlaceholder('首次生成日期').press('Enter');
  await dialog.getByPlaceholder('备注（可选），将写入生成的流水').fill(prefix);
  await dialog.getByRole('button', { name: /保\s*存/ }).click();
  await dialog.waitFor({ state: 'hidden' });
  const rule = (await api('GET', '/recurring')).find((entry) => entry.note === prefix);
  assert(rule); let removed = false;
  cleanup(async () => { if (!removed) await api('DELETE', `/recurring/${rule.id}`); });
  const row = page.locator(`[data-rule-id="${rule.id}"]`);
  await row.getByRole('button', { name: /暂\s*停/ }).click();
  await until(() => api('GET', '/recurring'), (rows) => rows.find((entry) => entry.id === rule.id)?.status === 'paused', 'pause');
  await row.getByRole('button', { name: /启\s*用/ }).click();
  await until(() => api('GET', '/recurring'), (rows) => rows.find((entry) => entry.id === rule.id)?.status === 'enabled', 'enable');
  await row.getByRole('button', { name: /删\s*除/ }).click();
  await page.getByRole('tooltip').getByRole('button', { name: /确\s*定/ }).click();
  await row.waitFor({ state: 'hidden' }); removed = true;
  const memberApi = await fixtureApi(base, 'voucher-member');
  const foreign = await memberApi('POST', '/recurring', { amount: '1', freq: 'monthly', account_id: account.id, category_id: category.id, start_date: '2099-01-01', note: prefix + '-foreign' });
  cleanup(() => memberApi('DELETE', `/recurring/${foreign.id}`));
  const memberContext = await browser.newContext(); const memberPage = await memberContext.newPage();
  await login(memberPage, base, 'voucher-recorder');
  await memberPage.goto(base + '/recurring');
  await memberPage.locator('.page h2').waitFor();
  assert.equal(await memberPage.locator(`[data-rule-id="${foreign.id}"]`).count(), 0, 'other templates are private');
  await memberContext.close(); await context.close();
  console.log('PASS narrow recurring create/pause/enable/delete and foreign ownership');
});
