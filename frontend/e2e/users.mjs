import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { withFixture, fixtureApi, fixtureToken, login, fixturePageRequest as pageRequest, shot } from './support/fixture.mjs';

const base = process.env.USERS_E2E_BASE ?? 'http://127.0.0.1:5601';
const username = 'auth-user-' + randomUUID().slice(0, 8);
const password = 'InitialPass123';
const changed = 'ChangedPass456';
await withFixture(base, async (browser, cleanup) => {
  const api = await fixtureApi(base);
  const adminContext = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  const page = await adminContext.newPage();
  await login(page, base);
  await page.goto(base + '/mine');
  await page.getByRole('button', { name: '用户管理', exact: true }).click();
  await page.locator('.ant-card-head-title').filter({ hasText: '用户管理' }).waitFor();
  const lastAdmin = page.locator('tbody tr.ant-table-row').filter({ hasText: 'voucher-admin' });
  assert.equal(await lastAdmin.locator('.ant-select-disabled').count(), 1);
  assert(await lastAdmin.getByRole('button', { name: /停\s*用/ }).isDisabled());
  const admin = (await api('GET', '/users')).find((user) => user.username === 'voucher-admin');
  await api('PATCH', '/users/' + admin.id + '/role', { role: 'member' }, 409);
  await api('PATCH', '/users/' + admin.id + '/status', { status: 'disabled' }, 409);

  await page.getByRole('button', { name: /新建用户/ }).click();
  const modal = page.getByRole('dialog', { name: '新建用户', exact: true });
  await modal.getByPlaceholder('登录用，如：xiaoming').fill(username);
  await modal.getByPlaceholder('至少 6 位，首次登录后可重置').fill(password);
  await modal.locator('.ant-select').click();
  await page.locator('.ant-select-dropdown:visible').getByText('只读成员', { exact: true }).click();
  await modal.getByRole('button', { name: /创\s*建/ }).click();
  await modal.waitFor({ state: 'hidden' });
  await page.locator('tbody tr.ant-table-row').filter({ hasText: username }).waitFor();
  const user = (await api('GET', '/users')).find((row) => row.username === username);
  assert.equal(user.role, 'viewer');
  cleanup(() => api('PATCH', '/users/' + user.id + '/status', { status: 'disabled' }));
  await api('POST', '/users', { username, password, role: 'viewer' }, 409);
  await shot(page, 'users-multi-device-desktop');
  console.log('PASS isolated user creation, duplicate name, last-admin UI and API protection');

  const targetContext = await browser.newContext();
  const target = await targetContext.newPage();
  await login(target, base, username, password);
  await target.goto(base + '/mine');
  assert.equal(await target.getByRole('button', { name: '用户管理', exact: true }).count(), 0);
  assert.equal((await pageRequest(target, 'GET', '/users')).status, 403);
  const cash = await pageRequest(target, 'POST', '/accounts', { name: '权限验收现金', type: 'asset', opening_balance: '0', request_key: randomUUID() });
  const category = await pageRequest(target, 'POST', '/categories', { name: '权限验收分类', kind: 'expense' });
  assert.equal(cash.status,200); assert.equal(category.status,200);
  assert.equal((await pageRequest(target, 'POST', '/transactions', { kind: 'expense', amount: '1', account_id: cash.body.data.id, category_id: category.body.data.id, entry_date: '2026-10-28' })).status, 403);
  const signOutTarget = async () => {
    await target.evaluate(() => window.dispatchEvent(new Event('focus')));
    await target.waitForURL(/\/login$/);
  };
  await api('PATCH', '/users/' + user.id + '/role', { role: 'member' });
  await signOutTarget();
  await login(target, base, username, password);
  await target.goto(base + '/');
  await target.getByRole('button', { name: /快捷记账$/ }).waitFor();
  assert.equal(await target.getByRole('button', { name: /快捷记账$/ }).count(), 1);

  await api('POST', '/users/' + user.id + '/password', { password: changed });
  await signOutTarget();
  const oldPassword = await targetContext.request.post(base + '/api/v1/auth/login', { data: { protocol_version: 2, username, password } });
  assert.equal(oldPassword.status(), 401);
  await login(target, base, username, changed);
  const state = fixtureToken(base,username);
  await api('PATCH', '/users/' + user.id + '/status', { status: 'disabled' });
  await signOutTarget();
  const disabled = await targetContext.request.post(base + '/api/v1/auth/login', { data: { protocol_version: 2, username, password: changed } });
  assert.equal(disabled.status(), 401);
  await api('PATCH', '/users/' + user.id + '/status', { status: 'active' });
  const previous = await targetContext.request.get(base + '/api/v1/auth/me', { headers: { Authorization: 'Bearer ' + state } });
  assert.equal(previous.status(), 401);
  await login(target, base, username, changed);
  console.log('PASS role/password/status operations revoke old sessions; restoring account requires fresh login');

  const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 }, userAgent: 'Mozilla/5.0 (iPhone) Mobile', hasTouch: true });
  const mobile = await mobileContext.newPage();
  await login(mobile, base);
  await mobile.goto(base + '/mine');
  await mobile.getByRole('button', { name: '用户管理', exact: true }).click();
  await mobile.getByText(username).first().waitFor();
  assert(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await shot(mobile, 'users-multi-device-mobile');
  console.log('PASS mobile user management layout; all writes confined to the disposable fixture');
}, 'chromium');
